import 'photo_state.dart';
import 'project_model.dart';

enum PresetKindModel { look, photo, template, export }

class PresetModel {
  final String id;
  final int schemaVersion;
  final String name;
  final String category;
  final String description;
  final PresetKindModel kind;
  final String mediaCompatibility;
  final PhotoAdjustments adjustments;
  final double vignette;
  final double sharpening;
  final double clarity;
  final double grain;
  final LutPresetModel lutPreset;
  final double lutIntensity;
  final double? audioEqLowGain;
  final double? audioEqMidGain;
  final double? audioEqHighGain;
  final String colorSpaceAssumptions;
  final bool isBuiltin;
  bool isFavorite;
  final String createdAt;
  final String modifiedAt;

  PresetModel({
    required this.id,
    this.schemaVersion = 1,
    required this.name,
    required this.category,
    this.description = '',
    required this.kind,
    this.mediaCompatibility = 'Universal',
    required this.adjustments,
    this.vignette = 0.0,
    this.sharpening = 0.0,
    this.clarity = 0.0,
    this.grain = 0.0,
    this.lutPreset = LutPresetModel.none,
    this.lutIntensity = 0.0,
    this.audioEqLowGain,
    this.audioEqMidGain,
    this.audioEqHighGain,
    this.colorSpaceAssumptions = 'Rec.709 / Linear sRGB',
    this.isBuiltin = false,
    this.isFavorite = false,
    String? createdAt,
    String? modifiedAt,
  })  : createdAt = createdAt ?? DateTime.now().toIso8601String(),
        modifiedAt = modifiedAt ?? DateTime.now().toIso8601String();

  PresetModel copyWith({
    String? id,
    int? schemaVersion,
    String? name,
    String? category,
    String? description,
    PresetKindModel? kind,
    String? mediaCompatibility,
    PhotoAdjustments? adjustments,
    double? vignette,
    double? sharpening,
    double? clarity,
    double? grain,
    LutPresetModel? lutPreset,
    double? lutIntensity,
    double? audioEqLowGain,
    double? audioEqMidGain,
    double? audioEqHighGain,
    String? colorSpaceAssumptions,
    bool? isBuiltin,
    bool? isFavorite,
    String? createdAt,
    String? modifiedAt,
  }) {
    return PresetModel(
      id: id ?? this.id,
      schemaVersion: schemaVersion ?? this.schemaVersion,
      name: name ?? this.name,
      category: category ?? this.category,
      description: description ?? this.description,
      kind: kind ?? this.kind,
      mediaCompatibility: mediaCompatibility ?? this.mediaCompatibility,
      adjustments: adjustments ?? this.adjustments.copyWith(),
      vignette: vignette ?? this.vignette,
      sharpening: sharpening ?? this.sharpening,
      clarity: clarity ?? this.clarity,
      grain: grain ?? this.grain,
      lutPreset: lutPreset ?? this.lutPreset,
      lutIntensity: lutIntensity ?? this.lutIntensity,
      audioEqLowGain: audioEqLowGain ?? this.audioEqLowGain,
      audioEqMidGain: audioEqMidGain ?? this.audioEqMidGain,
      audioEqHighGain: audioEqHighGain ?? this.audioEqHighGain,
      colorSpaceAssumptions: colorSpaceAssumptions ?? this.colorSpaceAssumptions,
      isBuiltin: isBuiltin ?? this.isBuiltin,
      isFavorite: isFavorite ?? this.isFavorite,
      createdAt: createdAt ?? this.createdAt,
      modifiedAt: modifiedAt ?? this.modifiedAt,
    );
  }

  /// Blends preset adjustments and effects with an intensity factor in [0.0, 1.0].
  PresetModel blendWithIntensity(double intensity) {
    final t = intensity.clamp(0.0, 1.0);
    return copyWith(
      adjustments: PhotoAdjustments(
        exposure: adjustments.exposure * t,
        contrast: adjustments.contrast * t,
        temperature: adjustments.temperature * t,
        tint: adjustments.tint * t,
        highlights: adjustments.highlights * t,
        shadows: adjustments.shadows * t,
        saturation: adjustments.saturation * t,
        vibrance: adjustments.vibrance * t,
      ),
      vignette: vignette * t,
      sharpening: sharpening * t,
      clarity: clarity * t,
      grain: grain * t,
      lutIntensity: lutIntensity * t,
      audioEqLowGain: audioEqLowGain != null ? audioEqLowGain! * t : null,
      audioEqMidGain: audioEqMidGain != null ? audioEqMidGain! * t : null,
      audioEqHighGain: audioEqHighGain != null ? audioEqHighGain! * t : null,
    );
  }

  Map<String, dynamic> toJson() {
    return {
      'id': id,
      'schema_version': schemaVersion,
      'name': name,
      'category': category,
      'description': description,
      'kind': kind == PresetKindModel.look ? 'LookPreset' : (kind == PresetKindModel.photo ? 'PhotoPreset' : 'ProjectTemplate'),
      'media_compatibility': 'Universal',
      'adjustments': adjustments.toJson(),
      'vignette': vignette,
      'sharpening': sharpening,
      'clarity': clarity,
      'grain': grain,
      'lut_preset': null,
      'lut_intensity': lutIntensity,
      'levels': null,
      'audio_eq_low_gain': audioEqLowGain,
      'audio_eq_mid_gain': audioEqMidGain,
      'audio_eq_high_gain': audioEqHighGain,
      'color_space_assumptions': colorSpaceAssumptions,
      'supported_intensity_behavior': 'Linear',
      'is_builtin': isBuiltin,
      'is_favorite': isFavorite,
      'created_at': createdAt,
      'modified_at': modifiedAt,
    };
  }

  factory PresetModel.fromJson(Map<String, dynamic> json) {
    final kindStr = json['kind'] as String? ?? 'LookPreset';
    final kind = kindStr == 'PhotoPreset'
        ? PresetKindModel.photo
        : (kindStr == 'ProjectTemplate' ? PresetKindModel.template : PresetKindModel.look);

    final lutName = json['lut_preset'] as String? ?? '';
    LutPresetModel lut = LutPresetModel.none;
    for (final l in LutPresetModel.values) {
      if (l.name.toLowerCase() == lutName.toLowerCase() ||
          lutName.toLowerCase().contains(l.name.toLowerCase())) {
        lut = l;
        break;
      }
    }

    final adjMap = json['adjustments'] as Map<String, dynamic>? ?? {};

    return PresetModel(
      id: json['id'] as String? ?? 'preset_${DateTime.now().millisecondsSinceEpoch}',
      schemaVersion: json['schema_version'] as int? ?? 1,
      name: json['name'] as String? ?? 'Custom Preset',
      category: json['category'] as String? ?? 'Custom',
      description: json['description'] as String? ?? '',
      kind: kind,
      mediaCompatibility: json['media_compatibility'] as String? ?? 'Universal',
      adjustments: PhotoAdjustments.fromJson(adjMap),
      vignette: (json['vignette'] as num?)?.toDouble() ?? 0.0,
      sharpening: (json['sharpening'] as num?)?.toDouble() ?? 0.0,
      clarity: (json['clarity'] as num?)?.toDouble() ?? 0.0,
      grain: (json['grain'] as num?)?.toDouble() ?? 0.0,
      lutPreset: lut,
      lutIntensity: (json['lut_intensity'] as num?)?.toDouble() ?? 0.0,
      audioEqLowGain: (json['audio_eq_low_gain'] as num?)?.toDouble(),
      audioEqMidGain: (json['audio_eq_mid_gain'] as num?)?.toDouble(),
      audioEqHighGain: (json['audio_eq_high_gain'] as num?)?.toDouble(),
      colorSpaceAssumptions: json['color_space_assumptions'] as String? ?? 'Rec.709 / Linear sRGB',
      isBuiltin: json['is_builtin'] == true,
      isFavorite: json['is_favorite'] == true,
      createdAt: json['created_at'] as String?,
      modifiedAt: json['modified_at'] as String?,
    );
  }

