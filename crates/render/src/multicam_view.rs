/// Information about a single angle frame to present in the multi-camera grid.
pub struct MultiCamAngleView<'a> {
    pub frame: &'a VideoFrame,
    pub name: &'a str,
    pub is_active: bool,
}

/// Renders a multi-camera quad-view monitor display.
/// Arranges up to 4 camera angles in a 2x2 grid with camera tags and highlights the active angle.
pub fn render_multicam_grid(
    angles: &[MultiCamAngleView],
    out_width: u32,
    out_height: u32,
) -> VideoFrame {
    let mut out_frame = VideoFrame::new(
        Dimensions::new(out_width, out_height),
        PixelFormat::Rgba8,
        RationalTime::ZERO,
        RationalTime::new(1, 30),
    );

    // Fill with dark studio background (#0B0D13)
    for chunk in out_frame.data.as_chunks_mut::<4>().0 {
        chunk[0] = 11;
        chunk[1] = 13;
        chunk[2] = 19;
        chunk[3] = 255;
    }

    if angles.is_empty() {
        return out_frame;
    }

    let quad_w = out_width / 2;
    let quad_h = out_height / 2;

    // Grid coordinates: (0,0), (1,0), (0,1), (1,1)
    let positions = [(0, 0), (1, 0), (0, 1), (1, 1)];

    for (idx, angle_view) in angles.iter().take(4).enumerate() {
        let (gx, gy) = positions[idx];
        let start_x = gx * quad_w;
        let start_y = gy * quad_h;

        // Downscale source frame into quadrant using bilinear sampling
        blit_scaled_frame(
            &mut out_frame,
            angle_view.frame,
            start_x,
            start_y,
            quad_w,
            quad_h,
        );

        // If this angle is active/on-air, draw vibrant highlight border (Orange / Cyan)
        let border_color = if angle_view.is_active {
            [255, 138, 0] // Bright On-Air Orange
        } else {
            [40, 48, 64] // Muted inactive border
        };
        let border_thickness = if angle_view.is_active { 4 } else { 1 };
        draw_border(
            &mut out_frame,
            start_x as isize,
            start_y as isize,
            quad_w as isize,
            quad_h as isize,
            border_thickness,
            border_color,
        );

        // Draw camera title tag bar at bottom of quadrant
        let tag_h = 24isize;
        let tag_y = (start_y + quad_h) as isize - tag_h;
        fill_rect(
            &mut out_frame,
            start_x as isize,
            tag_y,
            quad_w as isize,
            tag_h,
            [15, 18, 26],
            0.85,
        );

        // Status pill indicator
        let pill_color = if angle_view.is_active {
            [255, 138, 0] // Active
        } else {
            [0, 209, 255] // Standby
        };
        fill_rect(
            &mut out_frame,
            start_x as isize + 8,
            tag_y + 8,
            8,
            8,
            pill_color,
            1.0,
        );

        // Camera name string
        let label = format!(
            "CAM {} - {}",
            idx + 1,
            if angle_view.is_active {
                format!("{} [ON-AIR]", angle_view.name)
            } else {
                angle_view.name.to_string()
            }
        );
        draw_string(
            &mut out_frame,
            &label,
            start_x as isize + 22,
            tag_y + 8,
            1,
            [240, 245, 250],
        );
    }

    out_frame
}

fn blit_scaled_frame(
    dst: &mut VideoFrame,
    src: &VideoFrame,
    dst_x: u32,
    dst_y: u32,
    dst_w: u32,
    dst_h: u32,
) {
    let src_w = src.dimensions.width as f32;
    let src_h = src.dimensions.height as f32;

    for dy in 0..dst_h {
        let sy = ((dy as f32 / dst_h as f32) * src_h).clamp(0.0, src_h - 1.0) as usize;
        let target_y = dst_y + dy;
        let dst_row = target_y as usize * dst.stride;
        let src_row = sy * src.stride;

        for dx in 0..dst_w {
            let sx = ((dx as f32 / dst_w as f32) * src_w).clamp(0.0, src_w - 1.0) as usize;
            let target_x = dst_x + dx;
            let dst_offset = dst_row + target_x as usize * 4;
            let src_offset = src_row + sx * 4;

            dst.data[dst_offset..dst_offset + 4]
                .copy_from_slice(&src.data[src_offset..src_offset + 4]);
        }
    }
}

fn draw_border(
    frame: &mut VideoFrame,
    x: isize,
    y: isize,
    w: isize,
    h: isize,
    thickness: isize,
    color: [u8; 3],
) {
    let fw = frame.dimensions.width as isize;
    let fh = frame.dimensions.height as isize;

    for ty in 0..thickness {
        // Top and Bottom horizontal edges
        for tx in 0..w {
            let px = x + tx;
            let py_top = y + ty;
            let py_bot = y + h - 1 - ty;

            if px >= 0 && px < fw {
                if py_top >= 0 && py_top < fh {
                    let offset = py_top as usize * frame.stride + px as usize * 4;
                    frame.data[offset..offset + 3].copy_from_slice(&color);
                }
                if py_bot >= 0 && py_bot < fh {
                    let offset = py_bot as usize * frame.stride + px as usize * 4;
                    frame.data[offset..offset + 3].copy_from_slice(&color);
                }
            }
        }

        // Left and Right vertical edges
        for ty_inner in 0..h {
            let py = y + ty_inner;
            let px_left = x + ty;
            let px_right = x + w - 1 - ty;

            if py >= 0 && py < fh {
                if px_left >= 0 && px_left < fw {
                    let offset = py as usize * frame.stride + px_left as usize * 4;
                    frame.data[offset..offset + 3].copy_from_slice(&color);
                }
                if px_right >= 0 && px_right < fw {
                    let offset = py as usize * frame.stride + px_right as usize * 4;
                    frame.data[offset..offset + 3].copy_from_slice(&color);
                }
            }
        }
    }
}

fn fill_rect(
    frame: &mut VideoFrame,
    x: isize,
    y: isize,
    w: isize,
    h: isize,
    color: [u8; 3],
    alpha: f32,
) {
    let fw = frame.dimensions.width as isize;
    let fh = frame.dimensions.height as isize;
    let inv_a = 1.0 - alpha;

    let x0 = x.clamp(0, fw);
    let x1 = (x + w).clamp(0, fw);
    let y0 = y.clamp(0, fh);
    let y1 = (y + h).clamp(0, fh);

    for py in y0..y1 {
        let row = py as usize * frame.stride;
        for px in x0..x1 {
            let offset = row + px as usize * 4;
            frame.data[offset] =
                (frame.data[offset] as f32 * inv_a + color[0] as f32 * alpha).round() as u8;
            frame.data[offset + 1] =
                (frame.data[offset + 1] as f32 * inv_a + color[1] as f32 * alpha).round() as u8;
            frame.data[offset + 2] =
                (frame.data[offset + 2] as f32 * inv_a + color[2] as f32 * alpha).round() as u8;
        }
    }
}

fn draw_string(
    frame: &mut VideoFrame,
    text: &str,
    start_x: isize,
    start_y: isize,
    scale: usize,
    color: [u8; 3],
) {
    let mut cursor_x = start_x;
    let fw = frame.dimensions.width as isize;
    let fh = frame.dimensions.height as isize;

    for ch in text.chars() {
        let ascii = ch as usize;
        let glyph_idx = if (32..=126).contains(&ascii) {
            ascii - 32
        } else {
            0
        };
        let bitmap = FONT_8X8[glyph_idx];

        for (row, &byte) in bitmap.iter().enumerate() {
            for col in 0..8 {
                if (byte & (1 << (7 - col))) != 0 {
                    for sy in 0..scale {
                        for sx in 0..scale {
                            let px = cursor_x + (col * scale + sx) as isize;
                            let py = start_y + (row * scale + sy) as isize;

                            if px >= 0 && px < fw && py >= 0 && py < fh {
                                let offset = py as usize * frame.stride + px as usize * 4;
                                frame.data[offset..offset + 3].copy_from_slice(&color);
                            }
                        }
                    }
                }
            }
        }

        cursor_x += (scale * 8 + 2) as isize;
    }
}
