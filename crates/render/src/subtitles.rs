pub fn render_subtitles_on_frame(
    frame: &mut VideoFrame,
    subtitle_tracks: &[SubtitleTrack],
    time: iris_core::RationalTime,
) -> IrisResult<()> {
    for track in subtitle_tracks {
        if !track.enabled {
            continue;
        }
        for item in track.items_at(time) {
            let style = item.style.as_ref().unwrap_or(&track.default_style);
            render_subtitle_item(frame, item, style);
        }
    }
    Ok(())
}

fn render_subtitle_item(frame: &mut VideoFrame, item: &SubtitleItem, style: &SubtitleStyle) {
    let scale = (style.font_size / 8).max(1) as usize;
    let char_w = 8 * scale;
    let char_h = 8 * scale;
    let line_spacing = 4 * scale;

    let lines: Vec<&str> = item.text.lines().collect();
    if lines.is_empty() {
        return;
    }

    let max_line_len = lines.iter().map(|l| l.chars().count()).max().unwrap_or(0);
    let text_block_w = max_line_len * char_w;
    let text_block_h = lines.len() * char_h + (lines.len().saturating_sub(1)) * line_spacing;

    let pad_x = 12 * scale;
    let pad_y = 8 * scale;
    let box_w = text_block_w + pad_x * 2;
    let box_h = text_block_h + pad_y * 2;

    let cw = frame.dimensions.width as usize;
    let ch = frame.dimensions.height as usize;

    let box_x = (cw.saturating_sub(box_w)) / 2;
    let box_y = match style.alignment {
        SubtitleAlignment::TopCenter => style.margin_bottom as usize,
        SubtitleAlignment::Center => (ch.saturating_sub(box_h)) / 2,
        SubtitleAlignment::BottomCenter => ch
            .saturating_sub(box_h)
            .saturating_sub(style.margin_bottom as usize),
    };

    // 1. Render background box if configured
    if let Some(bg) = style.bg_color {
        let opacity = bg[3] as f32 / 255.0;
        let bg_rgb = [bg[0], bg[1], bg[2], 255];

        for y in box_y..(box_y + box_h).min(ch) {
            let row_offset = y * cw * 4;
            for x in box_x..(box_x + box_w).min(cw) {
                let pixel_offset = row_offset + x * 4;
                let dst_col = [
                    frame.data[pixel_offset],
                    frame.data[pixel_offset + 1],
                    frame.data[pixel_offset + 2],
                    frame.data[pixel_offset + 3],
                ];
                let blended = blend_pixel(dst_col, bg_rgb, BlendMode::Normal, opacity);
                frame.data[pixel_offset..pixel_offset + 4].copy_from_slice(&blended);
            }
        }
    }

    // 2. Render each text line
    let text_color = [
        style.text_color[0],
        style.text_color[1],
        style.text_color[2],
        255,
    ];
    let text_opacity = style.text_color[3] as f32 / 255.0;

    for (line_idx, line) in lines.iter().enumerate() {
        let line_chars = line.chars().count();
        let line_w = line_chars * char_w;
        let line_x = (cw.saturating_sub(line_w)) / 2;
        let line_y = box_y + pad_y + line_idx * (char_h + line_spacing);

        for (ch_idx, c) in line.chars().enumerate() {
            let glyph_x = line_x + ch_idx * char_w;
            let glyph_y = line_y;
            draw_glyph(frame, c, glyph_x, glyph_y, scale, text_color, text_opacity);
        }
    }
}

fn draw_glyph(
    frame: &mut VideoFrame,
    c: char,
    start_x: usize,
    start_y: usize,
    scale: usize,
    color: [u8; 4],
    opacity: f32,
) {
    let ascii = c as u32;
    if !(32..=126).contains(&ascii) {
        return; // Non-ASCII printable skipped in fallback bitmap font
    }
    let glyph_idx = (ascii - 32) as usize;
    let bitmap = FONT_8X8[glyph_idx];

    let cw = frame.dimensions.width as usize;
    let ch = frame.dimensions.height as usize;

    for (row, &row_bits) in bitmap.iter().enumerate() {
        for col in 0..8 {
            let bit = (row_bits >> (7 - col)) & 1;
            if bit == 1 {
                for sy in 0..scale {
                    let py = start_y + row * scale + sy;
                    if py >= ch {
                        continue;
                    }
                    let row_offset = py * cw * 4;
                    for sx in 0..scale {
                        let px = start_x + col * scale + sx;
                        if px >= cw {
                            continue;
                        }
                        let pixel_offset = row_offset + px * 4;
                        let dst_col = [
                            frame.data[pixel_offset],
                            frame.data[pixel_offset + 1],
                            frame.data[pixel_offset + 2],
                            frame.data[pixel_offset + 3],
                        ];
                        let blended = blend_pixel(dst_col, color, BlendMode::Normal, opacity);
                        frame.data[pixel_offset..pixel_offset + 4].copy_from_slice(&blended);
                    }
                }
            }
        }
    }
}
